package com.daigorian.epcltvapp

/**
 * 番組名からシリーズ名を取り出す。
 *
 * 番組名は「シリーズ名 + その回に固有の情報」でできている。後者の始まりを見つけて
 * その手前までをシリーズ名とみなす。取り出した文字列は EPGStation のキーワード検索に
 * そのまま渡され、同じシリーズの他の回を引くのに使われる。
 *
 * Android に依存しないので、単体テストから直接呼べる。
 *
 * ## 規則
 *
 * 区切りの手掛かりは7種類ある。成立した位置のうち**最も左のもの**が採用される。
 *
 * | | 手掛かり |
 * |---|---|
 * | A1 | 話数記号 + 1〜3桁の数字。漢数字版は直前の空白が必須（後述） |
 * | A2 | 1〜3桁の数字 + 話数を表す語 |
 * | A3 | 丸カッコで囲まれた1〜3桁の数字 |
 * | A4 | 境界記号。ここから先が各回固有の内容であることを示す |
 * | A5 | 角カッコで囲まれた放送のタグ |
 * | A6 | 丸カッコで囲まれた放送のタグ |
 * | A7 | マーカーを持たない話数。「空白 + 語 + 2〜3桁の数字」の形 |
 *
 * A1〜A4 だけは直前の空白を一緒に吸収する。A5・A6 は吸収しない。
 *
 * ## 漢数字の扱い
 *
 * 話数は漢数字で書かれることがあるため、A1 は漢数字も受け付ける。ただし**漢数字版は
 * 直前の空白を必須**にしている。算用数字と違い、漢数字の「第N」は固有名詞の一部として
 * 現れることが多く（歴史上の出来事、企業名、学校名など）、そこで切ると名前を割って
 * しまうためである。空白は語の切れ目を示すので、空白を伴う「第N」は話数、直前の語と
 * 繋がっている「第N」は固有名詞の一部、と判別できる。
 *
 * 文字数の上限が算用数字より多いのは、漢数字は位取りをしないため。3桁を表すのに
 * 最大5文字を要する（例: 999 は「九百九十九」）。
 *
 * ## A7 と止め木
 *
 * A7 だけは記号を手掛かりにせず、数字の並びだけを頼りに切る。そのままでは
 * サブタイトルの中にたまたま現れた数字を話数と誤認して、シリーズ名を削りすぎる。
 * これを防ぐため、A7 が飲み込む語は [STOPPERS] を越えられない。
 *
 * 止め木は境界記号(A4)に丸カッコ・角カッコを加えて組み立てる。**A4 の記号は必ず
 * 止め木にも含まれる**必要があるため、この形で保証している。A4 で切ると決めた位置
 * より左で A7 が切ると、定義上シリーズ名を削ることになるからである。
 * 逆向きは成り立たない。丸カッコ・角カッコの中身は読み仮名・年号・レーティング・
 * 話数と様々で、開きカッコという文字だけでは切ってよいか決まらない。中身を見て
 * 判断するのが A3・A5・A6 の役割になる。
 *
 * ## 先頭の『』
 *
 * `『` は境界記号(A4)に入っているので、そのままでは `TVアニメ『作品名』#8` を
 * 「TVアニメ」で切ってしまう。ジャンルの名乗りだけがシリーズ名として残り、
 * 別作品どうしが同じシリーズにまとまってしまう。
 *
 * 『』は作品名を囲む記号なので、**番組名の先頭に置かれた『』の中身**はシリーズ名
 * そのものである。そこで区切りを探すより先に [leadingWorkTitle] を当て、成立したら
 * 中身をそのまま返す。先頭の判定で飲み込めるのは [PREFIXES] に載せた名乗りだけで、
 * ここもタグと同じ辞書方式にしてある。
 *
 * 先頭に限るのは、文中の『』は作品名とは限らないため。副題の中の引用(`番組名 #7「AとB『C』」`)
 * や、番組名に続く企画名(`番組名『特別企画』`)がこれに当たる。後者は境界記号として
 * 扱うのが正しく、その振る舞いは今までどおり A4 が受け持つ。
 *
 * ## 辞書について
 *
 * タグや話数マーカーの一覧は、実際に放送されている番組名を集めて出現数を数え、
 * 目視で選び出したもの。任意の `[〜]` にマッチさせるような汎用化はしていない。
 * 角カッコの中身が番組名の一部であることが実在するため、誤検知の危険が高い。
 */
object SeriesTitleExtractor {

    /** 角カッコで囲んで番組名に付く放送のタグ。 */
    private const val TAGS =
        "PG12相当|PG-12|PG12|R-15相当|R-15|R15\\+|R指定" +
        "|最終話|無料|SS|HV|[新字デ解再無映終多二生初吹手SN]"

    /** 境界記号。ここから先が各回固有の内容であることを示す。 */
    private const val BOUNDARY = "「【『<▽▼"

    /**
     * 話数に使われる漢数字。大字（壱弐参…）も含む。
     * 大字は本来は改ざん防止のための表記だが、アニメの話数表記として定着している。
     */
    private const val KANJI_NUM = "〇一二三四五六七八九十百" + "壱弐参肆伍陸漆捌玖拾佰"

    /**
     * A7 が越えられない文字。境界記号に丸カッコ・角カッコを加えたもの。
     * 境界記号を増やしたときに止め木への追加を忘れないよう、[BOUNDARY] から組み立てる。
     */
    private const val STOPPERS = BOUNDARY + "(（\\["

    private val delimiter = (
        "(?!^)((" +
            "[\\s　]?(" +
                "(?:EP|[#＃♯第])[0-9０-９]{1,3}" +                 // A1
                "|[0-9０-９]{1,3}(?:回戦|分版|話)" +                // A2
                "|[(（][0-9０-９]{1,3}[)）]" +                     // A3
                "|[$BOUNDARY]" +                                  // A4
            ")" +
            "|[\\s　][#＃♯第][$KANJI_NUM]{1,5}" +                  // A1(漢数字)
            "|\\[(?:$TAGS)\\]" +                                  // A5
            "|[(（](?:字幕版|字幕|吹替版|吹|後編|前編)[)）]" +        // A6
        ")|(" +
            "[\\s　][^0-9０-９\\s　$STOPPERS]+[\\s　]?[0-9０-９]{2,3}" +  // A7
        "))"
        ).toRegex()

    /**
     * 行頭のタグを取り除く。2個以上連続することがあるので繰り返し適用する。
     * 行頭のタグは区切りとしては働かない(先頭では切らないため)ので、先に消しておく。
     */
    private val leadingTags = "^(\\[(?:$TAGS)\\])+|\\(吹\\)".toRegex()

    /**
     * 『』の前に置かれるジャンルの名乗り。作品名の一部ではないので、シリーズ名から外す。
     *
     * 載せるのは**一般名詞のジャンル名**だけ。固有名詞の枠名(局が付けた番組枠の名前)は載せない。
     * 枠名はその局だけの慣習であり、枠そのものが1つのシリーズとして通用することもあるので、
     * 境界記号として切る今までの振る舞い(A4)のままでよい。
     *
     * タグの辞書と同じく、実在の番組名から拾った語をそのまま並べる。「アニメを表す語なら何でも」
     * のように正規表現でまとめて拾うことはしない。辞書に無い名乗りは A4 が切る。
     */
    private const val PREFIXES = "TVアニメ|アニメ|ドラマ"

    /** 番組名の先頭に置かれた『』。中身が作品名そのものになる。 */
    private val leadingWorkTitle = "^[\\s　]*(?:$PREFIXES)?[\\s　]*『([^』]+)』".toRegex()

    /**
     * 番組名からシリーズ名を取り出す。
     *
     * 区切りが1つも見つからない場合は、番組名そのものをシリーズ名とみなす。
     * 話数を持たず、記号を取り除くとシリーズ名そのものになる番組が実在するため。
     *
     * @return シリーズ名。取り出せるものが無ければ空文字。
     */
    fun extract(programName: String): String {
        val body = programName.replace(leadingTags, "")
        leadingWorkTitle.find(body)?.let { return it.groupValues[1].trim() }
        return body.split(delimiter)[0].trim()
    }
}
